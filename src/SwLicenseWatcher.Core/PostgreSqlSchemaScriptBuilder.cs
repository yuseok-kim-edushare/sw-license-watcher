namespace SwLicenseWatcher.Core;

public sealed class PostgreSqlSchemaScriptBuilder : ISchemaScriptBuilder
{
    public string Build(SqlServerStorageOptions options) =>
        string.Join(Environment.NewLine + Environment.NewLine, BuildBatches(options));

    public IReadOnlyList<string> BuildBatches(SqlServerStorageOptions options)
    {
        SqlIdentifierValidator.Validate(options, SqlIdentifierValidator.PostgreSqlMaxLength);
        var schema = Q(options.SchemaName);
        var pc = options.PcTable;
        var installedSoftware = options.InstalledSoftwareTable;
        var policy = options.SoftwarePolicyTable;
        var violation = options.SoftwareViolationTable;
        var staleHeartbeat = options.StaleHeartbeatNotificationTable;
        var uninstall = options.UninstallRequestTable;
        var license = options.SoftwareLicenseTable;
        var workerPin = options.WorkerUpdatePinTable;
        var userMessage = options.UserMessageTable;
        var statements = new List<string>
        {
            $"CREATE SCHEMA IF NOT EXISTS {schema}",
            CreatePc(schema, pc),
            CreateInstalledSoftware(schema, installedSoftware, pc),
            CreatePolicy(schema, policy),
            CreateViolation(schema, violation, pc, policy),
            CreateStaleHeartbeat(schema, staleHeartbeat, pc),
            CreateUninstall(schema, uninstall, pc),
            CreateLicense(schema, license, pc),
            CreateWorkerPin(schema, workerPin),
            CreateUserMessage(schema, userMessage, pc)
        };

        AddColumn(statements, schema, policy.TableName, policy.DefaultLicenseSourceColumn, "varchar(16)");
        AddColumn(statements, schema, pc.TableName, pc.AssignedHostNameColumn, "varchar(128)");
        AddColumn(statements, schema, pc.TableName, pc.AdminNotesColumn, "varchar(1024)");
        AddColumn(statements, schema, pc.TableName, pc.AssignedDeviceCodeColumn, "varchar(128)");
        AddColumn(statements, schema, pc.TableName, pc.DeviceIdColumn, "varchar(36)");
        AddColumn(statements, schema, pc.TableName, pc.DevicePublicKeyColumn, "text");
        AddColumn(statements, schema, pc.TableName, pc.DeviceCertificateColumn, "text");
        statements.Add(
            $"ALTER TABLE {schema}.{Q(uninstall.TableName)} ADD COLUMN IF NOT EXISTS {Q(uninstall.OriginColumn)} varchar(16) NOT NULL DEFAULT '{UninstallGrant.OriginAgent}'");

        AddPartialUniqueIndex(statements, schema, pc.TableName, pc.DeviceIdColumn);
        AddPartialUniqueIndex(statements, schema, pc.TableName, pc.AssignedDeviceCodeColumn);
        AddIndex(statements, schema, installedSoftware.TableName, installedSoftware.PcForeignKeyColumn);
        AddIndex(statements, schema, installedSoftware.TableName, installedSoftware.ClassificationColumn);
        AddIndex(statements, schema, policy.TableName, policy.ClassificationColumn);
        AddIndex(statements, schema, violation.TableName, violation.PolicyForeignKeyColumn);
        AddIndex(statements, schema, uninstall.TableName, uninstall.PcForeignKeyColumn);
        AddIndex(statements, schema, uninstall.TableName, uninstall.StatusColumn);
        AddIndex(statements, schema, license.TableName, license.PcForeignKeyColumn);
        AddIndex(statements, schema, userMessage.TableName, userMessage.PcForeignKeyColumn);
        AddIndex(statements, schema, userMessage.TableName, userMessage.StatusColumn);
        return statements;
    }

    private static string CreatePc(string schema, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(pc.TableName)} (
            {Q(pc.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(pc.DeviceCodeColumn)} varchar(128) NOT NULL,
            {Q(pc.HostNameColumn)} varchar(128) NOT NULL,
            {Q(pc.DomainNameColumn)} varchar(128) NOT NULL,
            {Q(pc.OperatingSystemColumn)} varchar(128) NOT NULL,
            {Q(pc.AgentVersionColumn)} varchar(32) NOT NULL,
            {Q(pc.LastHeartbeatUtcColumn)} timestamptz NULL,
            {Q(pc.LastInventoryUtcColumn)} timestamptz NULL,
            {Q(pc.AssignedHostNameColumn)} varchar(128) NULL,
            {Q(pc.AdminNotesColumn)} varchar(1024) NULL,
            {Q(pc.AssignedDeviceCodeColumn)} varchar(128) NULL,
            {Q(pc.DeviceIdColumn)} varchar(36) NULL,
            {Q(pc.DevicePublicKeyColumn)} text NULL,
            {Q(pc.DeviceCertificateColumn)} text NULL,
            CONSTRAINT {Q(Ident("UX", pc.TableName, pc.DeviceCodeColumn))} UNIQUE ({Q(pc.DeviceCodeColumn)})
        )
        """;

    private static string CreateInstalledSoftware(string schema, InstalledSoftwareTableOptions software, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(software.TableName)} (
            {Q(software.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(software.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(software.DisplayNameColumn)} varchar(256) NOT NULL,
            {Q(software.DisplayVersionColumn)} varchar(64) NULL,
            {Q(software.PublisherColumn)} varchar(256) NULL,
            {Q(software.InstallLocationColumn)} varchar(512) NULL,
            {Q(software.DiscoveryScopeColumn)} varchar(256) NOT NULL,
            {Q(software.DiscoverySourceColumn)} varchar(64) NOT NULL,
            {Q(software.ClassificationColumn)} varchar(32) NOT NULL,
            {Q(software.CollectedAtUtcColumn)} timestamptz NOT NULL,
            CONSTRAINT {Q(Ident("FK", software.TableName, pc.TableName))} FOREIGN KEY ({Q(software.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)})
        )
        """;

    private static string CreatePolicy(string schema, SoftwarePolicyTableOptions policy) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(policy.TableName)} (
            {Q(policy.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(policy.ClassificationColumn)} varchar(32) NOT NULL,
            {Q(policy.ProductNameColumn)} varchar(256) NOT NULL,
            {Q(policy.PublisherColumn)} varchar(256) NULL,
            {Q(policy.VersionPatternColumn)} varchar(64) NULL,
            {Q(policy.NotesColumn)} varchar(1024) NULL,
            {Q(policy.EnabledColumn)} boolean NOT NULL DEFAULT TRUE,
            {Q(policy.UpdatedAtUtcColumn)} timestamptz NOT NULL,
            {Q(policy.DefaultLicenseSourceColumn)} varchar(16) NULL
        )
        """;

    private static string CreateViolation(
        string schema,
        SoftwareViolationTableOptions violation,
        PcTableOptions pc,
        SoftwarePolicyTableOptions policy) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(violation.TableName)} (
            {Q(violation.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(violation.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(violation.PolicyForeignKeyColumn)} bigint NOT NULL,
            {Q(violation.DisplayNameColumn)} varchar(256) NOT NULL,
            {Q(violation.DisplayVersionColumn)} varchar(64) NULL,
            {Q(violation.PublisherColumn)} varchar(256) NULL,
            {Q(violation.DetectedAtUtcColumn)} timestamptz NOT NULL,
            {Q(violation.LastSeenAtUtcColumn)} timestamptz NOT NULL,
            CONSTRAINT {Q(Ident("FK", violation.TableName, pc.TableName))} FOREIGN KEY ({Q(violation.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)}) ON DELETE CASCADE,
            CONSTRAINT {Q(Ident("FK", violation.TableName, policy.TableName))} FOREIGN KEY ({Q(violation.PolicyForeignKeyColumn)}) REFERENCES {schema}.{Q(policy.TableName)} ({Q(policy.PrimaryKeyColumn)}) ON DELETE CASCADE,
            CONSTRAINT {Q(Ident("UX", violation.TableName, violation.PcForeignKeyColumn, violation.DisplayNameColumn))} UNIQUE ({Q(violation.PcForeignKeyColumn)}, {Q(violation.DisplayNameColumn)})
        )
        """;

    private static string CreateStaleHeartbeat(string schema, StaleHeartbeatNotificationTableOptions stale, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(stale.TableName)} (
            {Q(stale.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(stale.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(stale.NotifiedAtUtcColumn)} timestamptz NOT NULL,
            CONSTRAINT {Q(Ident("FK", stale.TableName, pc.TableName))} FOREIGN KEY ({Q(stale.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)}) ON DELETE CASCADE,
            CONSTRAINT {Q(Ident("UX", stale.TableName, stale.PcForeignKeyColumn))} UNIQUE ({Q(stale.PcForeignKeyColumn)})
        )
        """;

    private static string CreateUninstall(string schema, UninstallRequestTableOptions uninstall, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(uninstall.TableName)} (
            {Q(uninstall.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(uninstall.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(uninstall.StatusColumn)} varchar(16) NOT NULL,
            {Q(uninstall.RequestedAtUtcColumn)} timestamptz NOT NULL,
            {Q(uninstall.ApprovedAtUtcColumn)} timestamptz NULL,
            {Q(uninstall.ConsumedAtUtcColumn)} timestamptz NULL,
            {Q(uninstall.ExpiresAtUtcColumn)} timestamptz NULL,
            {Q(uninstall.CodeHashColumn)} varchar(64) NULL,
            {Q(uninstall.CodeColumn)} varchar(16) NULL,
            {Q(uninstall.OriginColumn)} varchar(16) NOT NULL DEFAULT '{UninstallGrant.OriginAgent}',
            CONSTRAINT {Q(Ident("FK", uninstall.TableName, pc.TableName))} FOREIGN KEY ({Q(uninstall.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)}) ON DELETE CASCADE
        )
        """;

    private static string CreateLicense(string schema, SoftwareLicenseTableOptions license, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(license.TableName)} (
            {Q(license.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(license.SoftwareNameColumn)} varchar(256) NOT NULL,
            {Q(license.LicenseSourceColumn)} varchar(16) NOT NULL,
            {Q(license.UpdatedAtUtcColumn)} timestamptz NOT NULL,
            CONSTRAINT {Q(Ident("UX", license.TableName, license.PcForeignKeyColumn, license.SoftwareNameColumn))} UNIQUE ({Q(license.PcForeignKeyColumn)}, {Q(license.SoftwareNameColumn)}),
            CONSTRAINT {Q(Ident("FK", license.TableName, pc.TableName))} FOREIGN KEY ({Q(license.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)}) ON DELETE CASCADE
        )
        """;

    private static string CreateWorkerPin(string schema, WorkerUpdatePinTableOptions pin) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(pin.TableName)} (
            {Q(pin.TargetServiceNameColumn)} varchar(128) NOT NULL,
            {Q(pin.VersionColumn)} varchar(32) NOT NULL,
            {Q(pin.PackageUrlColumn)} varchar(2048) NOT NULL,
            {Q(pin.Sha256Column)} varchar(64) NOT NULL,
            {Q(pin.RequireAuthenticodeColumn)} boolean NOT NULL DEFAULT TRUE,
            {Q(pin.RollbackAfterMinutesColumn)} integer NOT NULL,
            {Q(pin.UpdatedAtUtcColumn)} timestamptz NOT NULL,
            CONSTRAINT {Q(Ident("PK", pin.TableName))} PRIMARY KEY ({Q(pin.TargetServiceNameColumn)})
        )
        """;

    private static string CreateUserMessage(string schema, UserMessageTableOptions message, PcTableOptions pc) => $"""
        CREATE TABLE IF NOT EXISTS {schema}.{Q(message.TableName)} (
            {Q(message.PrimaryKeyColumn)} bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            {Q(message.PcForeignKeyColumn)} bigint NOT NULL,
            {Q(message.TitleColumn)} varchar(128) NOT NULL,
            {Q(message.BodyColumn)} varchar(1024) NOT NULL,
            {Q(message.StatusColumn)} varchar(16) NOT NULL,
            {Q(message.CreatedAtUtcColumn)} timestamptz NOT NULL,
            {Q(message.ConsumedAtUtcColumn)} timestamptz NULL,
            CONSTRAINT {Q(Ident("FK", message.TableName, pc.TableName))} FOREIGN KEY ({Q(message.PcForeignKeyColumn)}) REFERENCES {schema}.{Q(pc.TableName)} ({Q(pc.PrimaryKeyColumn)}) ON DELETE CASCADE
        )
        """;

    private static void AddColumn(List<string> statements, string schema, string table, string column, string definition) =>
        statements.Add($"ALTER TABLE {schema}.{Q(table)} ADD COLUMN IF NOT EXISTS {Q(column)} {definition}");

    private static void AddIndex(List<string> statements, string schema, string table, string column)
    {
        var name = Ident("IX", table, column);
        statements.Add($"CREATE INDEX IF NOT EXISTS {Q(name)} ON {schema}.{Q(table)} ({Q(column)})");
    }

    private static void AddPartialUniqueIndex(List<string> statements, string schema, string table, string column)
    {
        var name = Ident("UX", table, column);
        statements.Add($"CREATE UNIQUE INDEX IF NOT EXISTS {Q(name)} ON {schema}.{Q(table)} ({Q(column)}) WHERE {Q(column)} IS NOT NULL");
    }

    private static string Ident(string prefix, params string[] parts) =>
        SchemaIdentifiers.Build(prefix, SqlIdentifierValidator.PostgreSqlMaxLength, parts);

    private static string Q(string identifier) => $"\"{identifier.Replace("\"", "\"\"", StringComparison.Ordinal)}\"";
}
