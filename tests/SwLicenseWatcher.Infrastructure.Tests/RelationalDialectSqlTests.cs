using SwLicenseWatcher.Core;
using SwLicenseWatcher.Infrastructure.Relational;

namespace SwLicenseWatcher.Infrastructure.Tests;

public class RelationalDialectSqlTests
{
    [Fact]
    public void MySql_list_uses_limit_and_unqualified_tables()
    {
        var sql = Context(MySqlDialect.Instance).BuildListPoliciesSql();
        Assert.Contains("LIMIT @take OFFSET @skip", sql, StringComparison.Ordinal);
        Assert.DoesNotContain("TOP ", sql, StringComparison.Ordinal);
        Assert.DoesNotContain("OFFSET @skip ROWS", sql, StringComparison.Ordinal);
        Assert.Contains("`software_policy_list`", sql, StringComparison.Ordinal);
        Assert.DoesNotContain("`inventory`", sql, StringComparison.Ordinal);
    }

    [Fact]
    public void MySql_like_uses_escape_clause()
    {
        var sql = Context(MySqlDialect.Instance).BuildListViolationsSql();
        Assert.Contains("LIKE @search ESCAPE '!'", sql, StringComparison.Ordinal);
        Assert.Equal("%100!%%", MySqlDialect.Instance.ToContainsPattern("100%"));
    }

    [Fact]
    public void MySql_upserts_use_duplicate_key_and_per_row_broadcast()
    {
        var context = Context(MySqlDialect.Instance);
        var pin = context.BuildUpsertWorkerUpdatePinSql();
        Assert.Contains("ON DUPLICATE KEY UPDATE", pin, StringComparison.Ordinal);
        Assert.DoesNotContain("MERGE ", pin, StringComparison.Ordinal);
        Assert.Contains("ON DUPLICATE KEY UPDATE", context.BuildUpsertSoftwareLicenseSql(), StringComparison.Ordinal);
        Assert.DoesNotContain("OUTPUT ", context.BuildInsertUserMessageSql(), StringComparison.Ordinal);
        Assert.DoesNotContain("RETURNING", context.BuildInsertUserMessageSql(), StringComparison.Ordinal);
        Assert.DoesNotContain("MERGE ", context.BuildBroadcastUserMessagesSql(), StringComparison.Ordinal);
        Assert.DoesNotContain("OUTPUT ", context.BuildInsertPolicySql(), StringComparison.Ordinal);
    }

    [Fact]
    public void PostgreSql_uses_conflict_returning_and_schema()
    {
        var context = Context(PostgreSqlDialect.Instance);
        var pin = context.BuildUpsertWorkerUpdatePinSql();
        Assert.Contains("ON CONFLICT", pin, StringComparison.Ordinal);
        Assert.Contains("RETURNING", pin, StringComparison.Ordinal);
        Assert.Contains("\"inventory\".\"worker_update_pin\"", pin, StringComparison.Ordinal);
        Assert.Contains("WITH inserted AS", context.BuildBroadcastUserMessagesSql(), StringComparison.Ordinal);
        Assert.Contains("DELETE FROM", context.BuildClearRecoveredStaleHeartbeatNotificationsSql(), StringComparison.Ordinal);
        Assert.DoesNotContain("DELETE n", context.BuildClearRecoveredStaleHeartbeatNotificationsSql(), StringComparison.Ordinal);
        Assert.Contains("OFFSET @skip ROWS FETCH NEXT @take ROWS ONLY", context.BuildListPoliciesSql(), StringComparison.Ordinal);
        Assert.Contains("= TRUE", context.BuildFindEnabledExactNamePolicySql(), StringComparison.Ordinal);
    }

    [Fact]
    public void MySql_schema_has_no_create_schema_and_uses_innodb()
    {
        var sql = new MySqlSchemaScriptBuilder().Build(new SqlServerStorageOptions());
        Assert.DoesNotContain("CREATE SCHEMA", sql, StringComparison.Ordinal);
        Assert.Contains("AUTO_INCREMENT", sql, StringComparison.Ordinal);
        Assert.Contains("ENGINE=InnoDB", sql, StringComparison.Ordinal);
        Assert.Contains("utf8mb4", sql, StringComparison.Ordinal);
        Assert.Contains("DATETIME(6)", sql, StringComparison.Ordinal);
        Assert.Contains("information_schema.COLUMNS", sql, StringComparison.Ordinal);
    }

    [Fact]
    public void PostgreSql_schema_uses_identity_timestamptz_and_partial_indexes()
    {
        var sql = new PostgreSqlSchemaScriptBuilder().Build(new SqlServerStorageOptions());
        Assert.Contains("CREATE SCHEMA IF NOT EXISTS \"inventory\"", sql, StringComparison.Ordinal);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql, StringComparison.Ordinal);
        Assert.Contains("timestamptz", sql, StringComparison.Ordinal);
        Assert.Contains("boolean NOT NULL DEFAULT TRUE", sql, StringComparison.Ordinal);
        Assert.Contains("WHERE \"device_id\" IS NOT NULL", sql, StringComparison.Ordinal);
        Assert.Contains("ADD COLUMN IF NOT EXISTS", sql, StringComparison.Ordinal);
    }

    private static RelationalDataContext Context(IRelationalDialect dialect) =>
        new(new SqlServerStorageOptions(), dialect);
}
